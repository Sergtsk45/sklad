_COMPILED = [(path, re.compile(pattern)) for path, pattern in RULES]


def normalize_name(name):
    """Нижний регистр и «ё» → «е» для сопоставления с правилами."""
    return (name or '').lower().replace('ё', 'е')


def match_category_path(name):
    """Вернуть путь категории для названия товара или None."""
    text = normalize_name(name)
    for path, regex in _COMPILED:
        if regex.search(text):
            return path
    return None
